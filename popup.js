// SubText - Minimalist YouTube Subtitle Extractor
// In-Tab Delegated Innertube Engine with Clean Editorial UI (Zero Emojis)

let currentMetadata = null;
let currentCaptionTracks = [];
let rawCaptionData = null;
let currentFormat = 'txt-prose';
let isPreviewVisible = true;
let activeTabId = null;

// DOM Elements
const statusDot = document.getElementById('status-dot');
const statusLabel = document.getElementById('status-label');
const videoCard = document.getElementById('video-card');
const videoIdEl = document.getElementById('video-id');
const videoTitleEl = document.getElementById('video-title');
const videoChannelEl = document.getElementById('video-channel');
const controlsSection = document.getElementById('controls-section');
const emptyState = document.getElementById('empty-state');
const emptyTitle = document.getElementById('empty-title');
const emptyDesc = document.getElementById('empty-desc');
const trackSelect = document.getElementById('track-select');
const tracksCountEl = document.getElementById('tracks-count');
const formatBtns = document.querySelectorAll('.seg-btn');
const previewText = document.getElementById('preview-text');
const togglePreviewBtn = document.getElementById('toggle-preview-btn');
const downloadBtn = document.getElementById('download-btn');
const downloadLabel = document.getElementById('download-btn-label');
const copyBtn = document.getElementById('copy-btn');
const copyLabel = document.getElementById('copy-btn-label');
