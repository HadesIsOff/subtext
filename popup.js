document.addEventListener('DOMContentLoaded', async () => {
  setupEventListeners();
  await inspectCurrentTab();
});

function setupEventListeners() {
  formatBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      formatBtns.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      currentFormat = btn.dataset.format;
      updateDownloadButtonLabel();
      renderSubtitleOutput();
    });
  });

  trackSelect.addEventListener('change', async () => {
    const selectedUrl = trackSelect.value;
    if (selectedUrl) {
      await loadCaptionContent(selectedUrl);
    }
  });

  togglePreviewBtn.addEventListener('click', () => {
    isPreviewVisible = !isPreviewVisible;
    previewText.style.display = isPreviewVisible ? 'block' : 'none';
    togglePreviewBtn.textContent = isPreviewVisible ? 'collapse' : 'expand';
  });

  downloadBtn.addEventListener('click', triggerDownload);
  copyBtn.addEventListener('click', triggerCopy);

  reloadTabBtn.addEventListener('click', async () => {
    if (activeTabId) {
      chrome.tabs.reload(activeTabId);
      window.close();
    }
  });
}

function extractVideoId(urlString) {
  try {
    const url = new URL(urlString);
    if (url.searchParams.has('v')) return url.searchParams.get('v');
    if (url.hostname === 'youtu.be') return url.pathname.slice(1);
    const shortsMatch = url.pathname.match(/\/shorts\/([a-zA-Z0-9_-]+)/);
    if (shortsMatch) return shortsMatch[1];
  } catch (e) {}
  return null;
}

// In-tab script that executes natively on https://www.youtube.com
async function inTabPageExtractor(targetVideoId) {
  try {
    let apiKey = window.ytcfg?.get?.('INNERTUBE_API_KEY');
    if (!apiKey) {
      const match = document.documentElement.innerHTML.match(/"INNERTUBE_API_KEY":"([^"]+)"/);
      apiKey = match ? match[1] : 'AIzaSyAO_FJ2SlqU8Q4STEHLGCilw_Y9_11qcW8';
    }

    const endpoint = `https://www.youtube.com/youtubei/v1/player?key=${apiKey}`;
    const payload = {
      context: {
        client: {
          clientName: 'ANDROID',
          clientVersion: '20.10.38',
          hl: 'en',
          gl: 'US'
        }
      },
      videoId: targetVideoId
    };

    const res = await fetch(endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });

    if (!res.ok) {
      return { error: `Innertube HTTP ${res.status}` };
    }

    const data = await res.json();
    const rawTracks = data?.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];

    const tracks = rawTracks.map(t => ({
      name: t.name?.simpleText || t.name?.runs?.[0]?.text || t.languageCode || 'Transcript',
      languageCode: t.languageCode || 'und',
      vssId: t.vssId || '',
      isAutoGenerated: (t.vssId && t.vssId.startsWith('a.')) || t.kind === 'asr',
      baseUrl: t.baseUrl
    }));

    return {
      title: data?.videoDetails?.title || document.title.replace(' - YouTube', ''),
      author: data?.videoDetails?.author || '',
      videoId: targetVideoId,
      tracks
    };
  } catch (err) {
    return { error: err.message };
  }
}

// In-tab caption fetcher: handles both direct and &tlang= auto-translations
async function inTabFetchCaption(captionUrl) {
  try {
    const res = await fetch(captionUrl);
    if (!res.ok) return { error: `Caption HTTP ${res.status}` };
    const text = await res.text();
    return { data: text };
  } catch (err) {
    return { error: err.message };
  }
}

async function inspectCurrentTab() {
  try {
    const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    if (!tab || !tab.url) {
      showError('No Active Tab', 'Unable to inspect current tab.');
      return;
    }

    activeTabId = tab.id;
    const videoId = extractVideoId(tab.url);
    if (!videoId) {
      showError(
        'Not a YouTube Video',
        'Open a video on youtube.com/watch?v=... and click SubText again.'
      );
      return;
    }

    setStatus('connecting', 'amber');
    videoIdEl.textContent = videoId;
    videoTitleEl.textContent = tab.title ? tab.title.replace(' - YouTube', '') : 'Fetching...';

    const results = await chrome.scripting.executeScript({
      target: { tabId: tab.id },
      world: 'MAIN',
      func: inTabPageExtractor,
      args: [videoId]
    });

    const result = results?.[0]?.result;

    if (!result || result.error) {
      throw new Error(result?.error || 'In-page extraction failed.');
    }

    currentMetadata = {
      videoId: videoId,
      title: result.title,
      author: result.author
    };

    displayMetadata(currentMetadata);

    if (!result.tracks || result.tracks.length === 0) {
      showNoCaptionsAvailable();
      return;
    }

    // Auto-generate English translated option if source is non-English
    currentCaptionTracks = buildTrackListWithTranslation(result.tracks);
    populateTracksDropdown(currentCaptionTracks);

    // Pick top track (English translated or native)
    const defaultTrack = currentCaptionTracks[0];
    trackSelect.value = defaultTrack.baseUrl;

    await loadCaptionContent(defaultTrack.baseUrl);
    setStatus('ready', 'green');
  } catch (err) {
    console.error('Inspection failed:', err);
    showError('Error', err.message || 'Failed to fetch transcript.');
    reloadTabBtn.style.display = 'block';
  }
}

function buildTrackListWithTranslation(tracks) {
  const list = [];
  const hasNativeEnglish = tracks.some(t => t.languageCode === 'en' || t.languageCode?.startsWith('en'));

  if (!hasNativeEnglish && tracks.length > 0) {
    const primarySource = tracks.find(t => t.isAutoGenerated) || tracks[0];
    list.push({
      name: `English (auto-translated from ${primarySource.name})`,
      languageCode: 'en',
      vssId: `t.en.${primarySource.languageCode}`,
      isAutoGenerated: true,
      isAutoTranslated: true,
      baseUrl: `${primarySource.baseUrl}&tlang=en`
    });
  }

  tracks.forEach(t => list.push(t));
  return list;
}

function displayMetadata(data) {
  videoIdEl.textContent = data.videoId || 'LIVE';
  videoTitleEl.textContent = data.title || 'Untitled Video';
  videoChannelEl.textContent = data.author ? `by ${data.author}` : '';
}

function populateTracksDropdown(tracks) {
  trackSelect.innerHTML = '';
  tracksCountEl.textContent = `${tracks.length} track${tracks.length === 1 ? '' : 's'}`;

  tracks.forEach(track => {
    const opt = document.createElement('option');
    opt.value = track.baseUrl;
    let label = '';
    if (track.isAutoTranslated) {
      label = `[EN] ${track.name}`;
    } else if (track.isAutoGenerated) {
      label = `[${track.languageCode.toUpperCase()}] ${track.name} (auto-captions)`;
    } else {
      label = `[${track.languageCode.toUpperCase()}] ${track.name} (manual)`;
    }
    opt.textContent = label;
    trackSelect.appendChild(opt);
  });

  controlsSection.style.display = 'flex';
  emptyState.style.display = 'none';
}

async function loadCaptionContent(baseUrl) {
  try {
    previewText.textContent = 'Fetching transcript stream...';

    const results = await chrome.scripting.executeScript({
      target: { tabId: activeTabId },
      world: 'MAIN',
      func: inTabFetchCaption,
      args: [baseUrl]
    });

    const res = results?.[0]?.result;
    if (!res || res.error || !res.data) {
      throw new Error(res?.error || 'Empty caption response.');
    }

    rawCaptionData = parseTimedTextXml(res.data);
    renderSubtitleOutput();
  } catch (err) {
    console.error('Caption load error:', err);
    previewText.textContent = `Error loading transcript: ${err.message}`;
  }
}

function parseTimedTextXml(xmlString) {
  const events = [];
  const parser = new DOMParser();
  const xml = parser.parseFromString(xmlString, 'text/xml');

  const pTags = xml.querySelectorAll('p');
  if (pTags.length > 0) {
    pTags.forEach(p => {
      const text = cleanHtmlEntities(p.textContent || '').trim();
      if (!text) return;

      const startMs = parseInt(p.getAttribute('t') || '0', 10);
      const durMs = parseInt(p.getAttribute('d') || '0', 10);
      events.push({
        startMs,
        endMs: startMs + durMs,
        text
      });
    });
    return events;
  }

  const textTags = xml.querySelectorAll('text');
  if (textTags.length > 0) {
    textTags.forEach(node => {
      const text = cleanHtmlEntities(node.textContent || '').trim();
      if (!text) return;

      const startSec = parseFloat(node.getAttribute('start') || '0');
      const durSec = parseFloat(node.getAttribute('dur') || '0');
      events.push({
        startMs: Math.round(startSec * 1000),
        endMs: Math.round((startSec + durSec) * 1000),
        text
      });
    });
    return events;
  }

  return events;
}

function cleanHtmlEntities(str) {
  return str
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/\n/g, ' ')
    .trim();
}

function formatTranscripts(events, format) {
  if (!events || events.length === 0) return '';

  switch (format) {
    case 'txt-prose':
      return events
        .map(e => e.text)
        .join(' ')
        .replace(/\s+/g, ' ')
        .replace(/([.?!])\s+/g, '$1\n\n')
        .trim();

    case 'txt-lines':
      return events.map(e => e.text).join('\n');

    case 'txt-stamps':
      return events.map(e => `[${formatTimestamp(e.startMs)}] ${e.text}`).join('\n');

    case 'srt':
      return events
        .map((e, idx) => {
          return `${idx + 1}\n${formatSrtTime(e.startMs)} --> ${formatSrtTime(e.endMs)}\n${e.text}\n`;
        })
        .join('\n');

    default:
      return events.map(e => e.text).join('\n');
  }
}

function renderSubtitleOutput() {
  if (!rawCaptionData || rawCaptionData.length === 0) {
    previewText.textContent = 'No text segments available in this track.';
    return;
  }

  const output = formatTranscripts(rawCaptionData, currentFormat);
  previewText.textContent = output;

  const words = output.trim() ? output.trim().split(/\s+/).length : 0;
  metricWords.textContent = words.toLocaleString();
  metricChars.textContent = output.length.toLocaleString();
  metricSegs.textContent = rawCaptionData.length.toLocaleString();
}

function updateDownloadButtonLabel() {
  const ext = currentFormat === 'srt' ? '.SRT' : '.TXT';
  downloadLabel.textContent = `DOWNLOAD ${ext}`;
}

function triggerDownload() {
  if (!rawCaptionData || rawCaptionData.length === 0) return;

  const content = formatTranscripts(rawCaptionData, currentFormat);
  const isSrt = currentFormat === 'srt';
  const ext = isSrt ? 'srt' : 'txt';
  const mime = isSrt ? 'application/x-subrip' : 'text/plain;charset=utf-8';

  const cleanTitle = (currentMetadata?.title || 'youtube_transcript')
    .replace(/[^a-zA-Z0-9_\- ]/g, '')
    .trim()
    .replace(/\s+/g, '_');

  const selectedTrack = currentCaptionTracks.find(t => t.baseUrl === trackSelect.value);
  const lang = selectedTrack?.languageCode || 'subtitles';
  const filename = `${cleanTitle}_${lang}.${ext}`;

  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);

  const original = downloadLabel.textContent;
  downloadLabel.textContent = 'SAVED';
  setTimeout(() => { downloadLabel.textContent = original; }, 1400);
}

async function triggerCopy() {
  if (!rawCaptionData || rawCaptionData.length === 0) return;

  const content = formatTranscripts(rawCaptionData, currentFormat);
  try {
    await navigator.clipboard.writeText(content);
    copyLabel.textContent = 'COPIED';
    copyBtn.style.borderColor = 'var(--accent-green)';
    setTimeout(() => {
      copyLabel.textContent = 'COPY';
      copyBtn.style.borderColor = 'var(--border)';
    }, 1400);
  } catch (err) {
    console.error('Clipboard copy failed:', err);
  }
}

function formatTimestamp(ms) {
  const totalSec = Math.floor(ms / 1000);
  const hrs = Math.floor(totalSec / 3600);
  const mins = Math.floor((totalSec % 3600) / 60);
  const secs = totalSec % 60;
  const pad = n => String(n).padStart(2, '0');
  if (hrs > 0) return `${pad(hrs)}:${pad(mins)}:${pad(secs)}`;
  return `${pad(mins)}:${pad(secs)}`;
}

function formatSrtTime(ms) {
  const totalSec = Math.floor(ms / 1000);
  const hrs = Math.floor(totalSec / 3600);
  const mins = Math.floor((totalSec % 3600) / 60);
  const secs = totalSec % 60;
  const millis = ms % 1000;
  const pad = (n, len = 2) => String(n).padStart(len, '0');
  return `${pad(hrs)}:${pad(mins)}:${pad(secs)},${pad(millis, 3)}`;
}

function setStatus(label, type) {
  statusLabel.textContent = label;
  statusDot.className = 'status-dot';
  if (type === 'green') statusDot.classList.add('active');
  if (type === 'red') statusDot.classList.add('error');
}

function showError(title, desc) {
  setStatus('error', 'red');
  controlsSection.style.display = 'none';
  emptyState.style.display = 'block';
  emptyTitle.textContent = title;
  emptyDesc.textContent = desc;
}

function showNoCaptionsAvailable() {
  setStatus('no captions', 'amber');
  controlsSection.style.display = 'none';
  emptyState.style.display = 'block';
  emptyTitle.textContent = 'No Subtitles Available';
  emptyDesc.textContent = 'This video does not have closed captions or transcripts.';
}
